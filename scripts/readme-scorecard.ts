/**
 * Regenerates the README scorecard tables from reports/ so the numbers cannot drift.
 *   npm run readme:scorecard          rewrite README.md between the markers
 *   npm run readme:scorecard -- --check   exit 1 if README.md is out of date (make check runs this)
 * Reads the reports written by `npm run eval:gate`.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readReports } from "../evals/runner/execute";
import { evaluateGate, type Gate } from "../evals/runner/gate";
import { loadBaseline, loadThresholds } from "../evals/runner/load";
import { buildScorecard, type Scorecard } from "../evals/runner/scorecard";
import type { SuiteReport } from "../evals/runner/types";

export const BEGIN = "<!-- scorecard:begin (generated by npm run readme:scorecard; do not edit) -->";
export const END = "<!-- scorecard:end -->";

const pct = (x: number | null) => (x === null ? "—" : `${(x * 100).toFixed(1)}%`);
const ids = (xs: readonly string[]) => xs.map((x) => `\`${x}\``).join(", ");

/** The README block: headline metrics and per-suite results. Deterministic for a given set of reports. */
export function renderReadmeScorecard(card: Scorecard, reports: readonly SuiteReport[], gate: Gate): string {
  const suiteRows = reports.map((r) => {
    const flaky = r.cases.filter((c) => c.flaky).map((c) => c.id);
    const failing = r.cases.filter((c) => c.stability === "stable-fail").map((c) => c.id);
    const ok = gate.results.find((g) => g.suite === r.suite)?.ok;
    const notes = [flaky.length ? `flaky: ${ids(flaky)}` : "", failing.length ? `always failing: ${ids(failing)}` : ""].filter(Boolean).join("; ");
    return `| ${r.suite} | ${r.cases.length} | ${pct(r.summary.passRate)} | ${flaky.length}/${r.cases.length} | ${notes || "—"} | ${ok ? "✅" : "❌"} |`;
  });
  return [
    `${card.mode === "mock" ? "Offline (mock)" : "Live"} run, N=${card.runsPerCase} runs per case, from \`npm run eval:gate\` (\`reports/scorecard.json\`):`,
    "",
    "| Metric | Value | What it measures |",
    "|---|---|---|",
    `| Pass rate (mean of suites) | ${pct(card.passRate)} | A run passes only if every scorer passes |`,
    `| Citation recall (Recall@k, rag) | ${pct(card.citationRecall)} | Expected document ids found in the returned citations |`,
    `| Grounding rate (rag) | ${pct(card.groundingRate)} | Faithfulness judge passes (mock judge: reference coverage) |`,
    `| Guardrail pass rate (rag) | ${pct(card.guardrailPassRate)} | Correct abstention when documents lack the answer |`,
    `| Tool-call accuracy (agent) | ${pct(card.toolCallAccuracy)} | Right tools, args and order |`,
    "| Latency p50 / p95 per run | see `reports/scorecard.json` | Varies per run, so it is not copied here |",
    "",
    "| Suite | Cases | Pass rate | Flaky cases | Seeded cases | Gate |",
    "|---|---|---|---|---|---|",
    ...suiteRows,
  ].join("\n");
}

/** Replaces the text between the markers. Throws if the markers are missing. */
export function replaceBlock(readme: string, block: string): string {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error(`README is missing the ${BEGIN} / ${END} markers`);
  return `${readme.slice(0, start + BEGIN.length)}\n${block}\n${readme.slice(end)}`;
}

/** Returns 0 when README is current (or was rewritten), 1 when --check finds drift. */
export async function syncReadme(opts: { check: boolean; readmePath?: string; reportsDir?: string; evalsDir?: string }): Promise<number> {
  const readmePath = opts.readmePath ?? "README.md";
  const reports = await readReports(opts.reportsDir);
  if (!reports.length) throw new Error("No reports found: run `npm run eval:gate` first");
  const gate = evaluateGate(reports, await loadThresholds(opts.evalsDir), await loadBaseline(reports[0]!.mode, opts.evalsDir));
  const current = await readFile(readmePath, "utf8");
  const next = replaceBlock(current, renderReadmeScorecard(buildScorecard(reports), reports, gate));
  if (next === current) return 0;
  if (opts.check) {
    console.error("README scorecard is out of date. Run `npm run eval:gate && npm run readme:scorecard` and commit README.md.");
    return 1;
  }
  await writeFile(readmePath, next);
  console.log("README scorecard updated.");
  return 0;
}

/* v8 ignore start -- process entry point; make check runs it for real */
const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) process.exitCode = await syncReadme({ check: process.argv.includes("--check") });
/* v8 ignore stop */
